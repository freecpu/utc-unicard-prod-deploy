#!/bin/bash
# ============================================================================
# compare-nested-jar.sh — 递归下钻：比对 fat jar 内嵌套 jar 的**内层**条目清单
#
# 为什么需要它（2026-11-05 实测触发）：
#   外层清单比对结果：291 条目里只有 3 条不同，且三条的**长度完全一致**、只有 CRC 变：
#     META-INF/maven/com.cnc.unicard/unicard-official/pom.properties  128 B
#     BOOT-INF/lib/unicard-common-1.0.0.jar                       236204 B
#     BOOT-INF/lib/unicard-data-1.0.0.jar                         298184 B
#   而全部 40 个 BOOT-INF/classes/ 条目（长度+CRC）逐条一致。
#
#   「等长 + CRC 变」正是同源两次构建的特征（嵌套 ZIP 内部条目时间戳变 → 字节变 →
#   CRC 变；但时间戳字段定宽、条目集不变 → 总长不变）。**但这是形态推断，不是证据。**
#   必须把嵌套 jar 取出来，对它内部再做一次 (长度, CRC-32, 名字) 清单比对：
#   内层清单不含时间戳，若相同 → 内部每个 class 的内容逐条一致 → 代码相同。
#
#   pom.properties 单独处理：它 128 字节，内容形如
#     #Generated by Maven / #<构建时间戳> / groupId= / artifactId= / version=
#   差异应只在以 # 开头的注释行（构建时间）。用「剔掉 # 行后的归一化 sha256」来证明，
#   这样既闭环又不需要把文件内容打印出来（生产文件一律不外泄正文）。
#
# 安全边界：只读源 jar。嵌套 jar 解到临时目录，退出即清理。
#           **不打印任何文件正文**；只输出长度、CRC、条目名、哈希。
# 用法： bash compare-nested-jar.sh <fat jar路径> [dump]
# 依赖： sudo、unzip、sha256sum、awk、sort、sed
# ============================================================================
set -uo pipefail

FAT="${1:-}"
MODE="${2:-hash}"
[ -n "$FAT" ] || { echo "用法: bash compare-nested-jar.sh <fat jar路径> [dump]" >&2; exit 2; }
command -v unzip >/dev/null 2>&1 || { echo "FATAL: 本机无 unzip" >&2; exit 4; }

SUDO="sudo -n"
$SUDO true 2>/dev/null || SUDO=""
$SUDO test -r "$FAT" || { echo "FATAL: 读不到（已用 sudo 测） $FAT" >&2; exit 3; }

WORK="/tmp/nestjar.$$"
# ★ root 解出来的文件属主是 root，当前用户读不了 → 内层 unzip 会静默失败得到空清单，
#   空清单哈希两边相同 = 典型假阳性。必须 chown 回来，且 chown 失败要报出来。
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK" || { echo "FATAL: 建不了临时目录" >&2; exit 3; }

echo "==== 源 fat jar ===="
echo "fat_jar      = $FAT"
echo "fat_sha256   = $($SUDO sha256sum "$FAT" | cut -d' ' -f1)"

# ---------------------------------------------------------------- pom.properties
echo ""
echo "==== pom.properties 归一化比对（剔掉 # 注释行，故构建时间不参与）===="
POM_ENTRY="META-INF/maven/com.cnc.unicard/unicard-official/pom.properties"
$SUDO unzip -o -q "$FAT" "$POM_ENTRY" -d "$WORK" >/dev/null 2>&1
$SUDO chown -R "$(id -u):$(id -g)" "$WORK" 2>/dev/null \
  || { echo "FATAL: chown 失败，后续内层读取会得到空清单（假阳性）" >&2; exit 3; }
if [ -r "$WORK/$POM_ENTRY" ]; then
  # 只留非 # 行；同时报出 # 行数，证明确实剔掉了东西而不是文件本来就空
  POM_NORM="$(sed '/^[[:space:]]*#/d' "$WORK/$POM_ENTRY" | LC_ALL=C sort | sha256sum | cut -d' ' -f1)"
  POM_HASH_LINES="$(sed -n '/^[[:space:]]*#/=' "$WORK/$POM_ENTRY" | wc -l | tr -d ' ')"
  POM_ALL_LINES="$(wc -l < "$WORK/$POM_ENTRY" | tr -d ' ')"
  echo "pom_bytes            = $(stat -c '%s' "$WORK/$POM_ENTRY")"
  echo "pom_total_lines      = ${POM_ALL_LINES}"
  echo "pom_comment_lines    = ${POM_HASH_LINES}   （已剔除，构建时间戳在这里）"
  echo "pom_normalized_sha256= ${POM_NORM}"
  if [ "${POM_ALL_LINES:-0}" = "0" ]; then
    echo "FATAL: pom.properties 是空的，归一化哈希无意义。" >&2; exit 5
  fi
else
  echo "FATAL: 解不出 $POM_ENTRY（可能路径不同）。不可当作「两边相同」。" >&2; exit 5
fi

# ---------------------------------------------------------------- 嵌套模块 jar
echo ""
echo "==== 嵌套自有模块 jar 的内层条目清单 ===="
NESTED="$($SUDO unzip -l "$FAT" 'BOOT-INF/lib/*' 2>/dev/null \
          | awk 'NR>3 && $4 ~ /\.(jar)$/ {print $4}' \
          | grep -Ei 'unicard|ryd|utc' | LC_ALL=C sort)"
NN="$(printf '%s\n' "$NESTED" | grep -c . )"
if [ "${NN:-0}" = "0" ]; then
  echo "FATAL: 没找到自有模块 jar。0 命中不可当作「两边相同」。" >&2; exit 5
fi
echo "nested_jar_count = ${NN}"

# ★ 必须用进程替换 `< <(...)` 而不是 `printf ... | while`：管道里的 while 跑在
#   子 shell，其中的 exit 5 只结束子 shell，主脚本照样以 0 退出 —— FATAL 会变成
#   「只打印一行、然后看起来成功了」，这是最容易骗过人的失效形态。
while IFS= read -r ent; do
  [ -n "$ent" ] || continue
  base="$(basename "$ent")"
  # ★ unzip -d 会**保留条目全路径**：解出来在 $WORK/BOOT-INF/lib/xxx.jar，
  #   不是 $WORK/xxx.jar。实测第一版按 basename 去读，必然读不到 → 触发 FATAL。
  #   （pom.properties 那段没踩到，因为它本来就用的是 $WORK/$POM_ENTRY 全路径。）
  ext="$WORK/$ent"
  rm -f "$ext"
  $SUDO unzip -o -q "$FAT" "$ent" -d "$WORK" >/dev/null 2>&1
  $SUDO chown -R "$(id -u):$(id -g)" "$WORK" 2>/dev/null
  if [ ! -r "$ext" ]; then
    echo "FATAL: 解不出嵌套 jar $ent（预期路径 $ext）。空结果不可当作相同" >&2; exit 5
  fi
  outer_bytes="$(stat -c '%s' "$ext")"
  outer_sha="$(sha256sum "$ext" | cut -d' ' -f1)"
  # 内层清单：同样只取 (长度, CRC-32, 名字)，时间戳不参与
  inner="$WORK/$base.inner.txt"
  unzip -v "$ext" 2>/dev/null \
    | awk 'NR>3 && NF>=8 && $1 ~ /^[0-9]+$/ && $7 ~ /^[0-9a-fA-F]+$/ {
             name=$8; for(i=9;i<=NF;i++) name=name" "$i;
             printf "%s %s %s\n", $1, $7, name
           }' \
    | LC_ALL=C sort > "$inner"
  cnt="$(wc -l < "$inner" | tr -d ' ')"
  ih="$(sha256sum "$inner" | cut -d' ' -f1)"
  echo ""
  echo "-- $ent"
  echo "   nested_bytes        = ${outer_bytes}"
  echo "   nested_sha256       = ${outer_sha}   （含时间戳，两边不同属正常）"
  echo "   inner_entry_count   = ${cnt}"
  echo "   inner_manifest_sha  = ${ih}   ← **判据：不含时间戳，同码则必相同**"
  # ★ 内层 0 条目 = 内层 unzip 失败，两边都会得同一个空哈希 → 假阳性。必须拦住。
  if [ "${cnt:-0}" = "0" ]; then
    echo "   FATAL: 内层清单为空，比对静默失效。" >&2; exit 5
  fi
  # 关心的 class 是否真在里头（否则清单相同也覆盖不到 UtcProperties）
  hit="$(grep -c 'UtcProperties' "$inner")"
  echo "   UtcProperties_hits  = ${hit}"
  # ★ 闭合最后一环：内层清单里唯一不同的那条是 META-INF/maven/<本模块>/pom.properties。
  #   只凭「等长 + CRC 变」推断它是构建时间戳差异，那是**形态推断，不是证据**。
  #   这里对它做和外层同样的归一化：剔掉 # 注释行后算 sha256。
  #   两边归一化哈希相同 → 差异确实只在注释（Maven 写入的构建时间），代码无关。
  ipom_ent="$(awk '{name=$3; for(i=4;i<=NF;i++) name=name" "$i; if (name ~ /META-INF\/maven\/.*pom\.properties$/) print name}' "$inner" | head -1)"
  if [ -n "$ipom_ent" ]; then
    rm -rf "$WORK/px"
    mkdir -p "$WORK/px"
    unzip -o -q "$ext" "$ipom_ent" -d "$WORK/px" >/dev/null 2>&1
    if [ -r "$WORK/px/$ipom_ent" ]; then
      ipl_all="$(wc -l < "$WORK/px/$ipom_ent" | tr -d ' ')"
      ipl_cmt="$(sed -n '/^[[:space:]]*#/=' "$WORK/px/$ipom_ent" | wc -l | tr -d ' ')"
      ipom_norm="$(sed '/^[[:space:]]*#/d' "$WORK/px/$ipom_ent" | LC_ALL=C sort | sha256sum | cut -d' ' -f1)"
      echo "   inner_pom_entry     = ${ipom_ent}"
      echo "   inner_pom_lines     = ${ipl_all}（其中 # 注释 ${ipl_cmt} 行已剔除）"
      echo "   inner_pom_norm_sha  = ${ipom_norm}   ← 两边相同即证明差异只在构建时间戳"
      if [ "${ipl_all:-0}" = "0" ]; then
        echo "   FATAL: 内层 pom.properties 为空，归一化哈希无意义。" >&2; exit 5
      fi
    else
      echo "   FATAL: 解不出内层 $ipom_ent，无法闭合最后一环。" >&2; exit 5
    fi
  else
    echo "   FATAL: 内层清单里没有 pom.properties，与预期不符，需人工复核。" >&2; exit 5
  fi
  if [ "$MODE" = "dump" ]; then
    OUT="/tmp/nested-inner-$base.txt"
    cp "$inner" "$OUT"
    echo "   inner_manifest_dump = ${OUT}"
  fi
done < <(printf '%s\n' "$NESTED")

echo ""
echo "==== 判读方法 ===="
echo "  两台机器各跑一次，逐项比："
echo "    inner_manifest_sha 相同 → 该模块 jar 内部每个条目长度+CRC 逐条一致"
echo "                              → 代码相同，测试机结论可外推到生产"
echo "    pom_normalized_sha256 相同 → pom.properties 差异只在 # 注释（构建时间）"
echo "    inner_pom_norm_sha 相同   → 嵌套 jar 内层唯一不同的那条也只是构建时间"
echo "    UtcProperties_hits 必须 > 0，否则本比对覆盖不到真正关心的那个类"
echo ""
echo "  ★ 只有当「内层清单不同的条目 = 仅 pom.properties」且「内外层 pom 归一化哈希都相同」"
echo "    两条同时成立时，才能下「同一份代码」的结论。缺一不可。"
